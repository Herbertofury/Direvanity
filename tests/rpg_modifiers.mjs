#!/usr/bin/env node
/** Exercise every expedition modifier from a genuine command-playthrough save, without editing state. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const bytes=readFileSync(process.argv[2]||'target/wasm32-unknown-unknown/wasm-release/dread_wasm.wasm');
const source=readFileSync(process.argv[3]||'dist/rpg-chapter-complete-save.json','utf8');
const a=(await WebAssembly.instantiate(bytes,{})).instance.exports;
const encoder=new TextEncoder(),decoder=new TextDecoder();
const input=value=>{const b=encoder.encode(typeof value==='string'?value:JSON.stringify(value));const p=a.input_buffer(b.length);new Uint8Array(a.memory.buffer,p,b.length).set(b);};
const output=(n=a.output_len())=>decoder.decode(new Uint8Array(a.memory.buffer,a.output_buffer(),n));
const snapshot=()=>JSON.parse(output(a.snapshot()));
const save=()=>output(a.save_game());
const pois=()=>JSON.parse(output(a.campaign_locations()));
const hero=()=>snapshot().units.find(u=>u.kind==='commander');
const distance=(p,q)=>Math.hypot(p.x-q.x,p.z-q.z);
const cmd=value=>{input(value);assert.equal(a.command(),0,`${JSON.stringify(value)}: ${output()}`);};
input(source);assert.equal(a.load_game(),0,output());
assert.equal(snapshot().campaign.chronicle.chapter,5);
assert.equal(snapshot().campaign.chronicle.expedition.attempts,0,'Start from the publicly earned pre-expedition checkpoint');
const profile=JSON.parse(output(a.class_catalogue())).classes.find(c=>c.id===snapshot().campaign.character.class_id);
function fight() {
  const w=snapshot(),h=hero();assert.ok(h&&w.status==='playing');
  const enemy=w.units.filter(u=>u.team==='enemy').sort((x,y)=>distance(h.position,x.position)-distance(h.position,y.position))[0];
  for(const skill of profile.skills.filter(s=>s.kind==='active'&&w.campaign.learned.includes(s.id))) {
    const c=snapshot().campaign;
    if(c.cooldowns[skill.id]||c.focus<skill.focus_cost)continue;
    if(skill.effect==='heal'&&h.hp<h.max_hp*.75)cmd({type:'cast_skill',skill:skill.id,target:h.position});
    else if(enemy&&!['heal','guard','dash'].includes(skill.effect)&&distance(h.position,enemy.position)<=skill.range)cmd({type:'cast_skill',skill:skill.id,target:enemy.position});
  }
  a.step(15);
}
function walk(target,tolerance=1800) {
  cmd({type:'move',units:[1],target,attack_move:true});
  for(let i=0;i<600;i++){if(distance(hero().position,target)<=tolerance)return;fight();}
  assert.fail('Movement did not reach its objective');
}
function interact(id){const poi=pois().find(p=>p.id===id);assert.ok(poi,`Missing ${id}`);walk(poi.position);cmd({type:'interact',target:id});}
function clear(){for(let i=0;i<600&&snapshot().units.some(u=>u.team==='enemy');i++){const h=hero();const enemy=snapshot().units.filter(u=>u.team==='enemy').sort((u,v)=>distance(h.position,u.position)-distance(h.position,v.position))[0];if(i%12===0)cmd({type:'move',units:[1],target:enemy.position,attack_move:true});fight();}assert.equal(snapshot().units.filter(u=>u.team==='enemy').length,0);}
function equip(){for(const slot of ['weapon','charm']){const best=snapshot().campaign.inventory.filter(i=>i.slot===slot).sort((x,y)=>y.power-x.power)[0];if(best)cmd({type:'equip',item:best.id});}}
const runs=[];
for(let depth=1;depth<=3;depth++) {
  interact('rift');const run=snapshot().campaign.chronicle.expedition.active;assert.equal(run.depth,depth);
  clear();if(run.objective==='seals')for(const id of ['seal_north','seal_south','seal_east'])interact(id);
  interact('claim');assert.equal(snapshot().campaign.chronicle.expedition.active.reward_claimed,true);
  const exact=save();input(exact);assert.equal(a.load_game(),0,output());assert.equal(save(),exact);
  runs.push({depth,objective:run.objective,modifier:run.modifier,remaining_health:hero().hp,tick:snapshot().tick});
  interact('exit');equip();interact('merchant');
}
assert.deepEqual([...new Set(runs.map(r=>r.modifier))].sort(),['drought','haste','wrath']);
const receipt={result:'passed',source:'Exact Paladin checkpoint generated by tests/rpg_abi.mjs from real initial seed 20261125; no save mutations',source_sha256:createHash('sha256').update(source).digest('hex'),wasm_sha256:createHash('sha256').update(bytes).digest('hex'),runs,verified:['all three modifiers exercised by actual combat','all three objectives completed','exact save reload after each reward','survived without HP/XP/world edits']};
mkdirSync('dist',{recursive:true});writeFileSync('dist/expedition-modifier-proof.json',JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt,null,2));
